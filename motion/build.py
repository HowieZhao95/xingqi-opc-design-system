"""将分镜、主题、品牌字标及字型嵌入本地脚本，支持 file:// 直接打开。"""
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent

def data_uri(path, mime):
    data = base64.b64encode(path.read_bytes()).decode('ascii')
    return f'data:{mime};base64,{data}'

plan = json.loads((ROOT / 'shot-plan.json').read_text())
colors = json.loads((ROOT / plan['tokens']).read_text())
assets = plan['local_assets']
fonts = {name: data_uri(ROOT / path, 'font/woff2') for name, path in assets['fonts'].items()}
logos = {name: data_uri(ROOT / path, 'image/svg+xml') for name, path in assets['logo'].items()}
bundle = {'plan': plan, 'tokens': colors, 'fonts': fonts, 'logos': logos}
(ROOT / 'compositions' / 'offline.js').write_text(
    '// Generated by build.py from shot-plan.json and shared assets.\n'
    + 'window.OPC_ASSETS=' + json.dumps(bundle, ensure_ascii=False, separators=(',', ':')) + ';\n')
